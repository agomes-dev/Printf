#include "ft_printf.h"

int	ft_putstr(char *s)
{
	int	i;

	i = 0;
	if (s == NULL)
		return (ft_putstr("(null)"));
	while (s[i] != '\0')
	{
		if (ft_putchar(s[i] == -1))
			return (-1);
		i++;
	}
	return (i);
}
